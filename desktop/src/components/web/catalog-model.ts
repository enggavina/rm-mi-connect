import type { DeleteCatalogInput, EditableCatalogKind, SaveCatalogInput } from '@/server/web/catalog-policy';
import type { WebActionResult } from '@/server/web/actions';
import type { SsoContext } from '@/server/web/auth-policy';

export const catalogLabels: Record<EditableCatalogKind, { singular: string; plural: string; create: string }> = {
  clients: { singular: 'cliente', plural: 'Clientes', create: 'Cadastrar cliente' },
  cells: { singular: 'célula', plural: 'Células', create: 'Cadastrar célula' },
  types: { singular: 'tipo de equipamento', plural: 'Tipos de equipamento', create: 'Cadastrar tipo de equipamento' },
};
export function editableKind(value: unknown): EditableCatalogKind | null {
  return value === 'clients' || value === 'cells' || value === 'types' ? value : null;
}
export function canManageCatalogs(access: { profile: { perfil: string }; sso?: Pick<SsoContext, 'capabilities'> }): boolean {
  return access.profile.perfil === 'administrador' && (!access.sso || access.sso.capabilities.includes('em.catalogs.manage'));
}
export type CatalogFields = Record<string, string>;
export function readCatalogForm(kind: EditableCatalogKind, form: FormData): { changes: SaveCatalogInput['changes']; errors: CatalogFields } {
  const text = (name: string) => String(form.get(name) ?? '').trim();
  const changes: Record<string, string | number | null> = { nome: text('nome') };
  const errors: CatalogFields = {};
  if (!changes.nome) errors.nome = 'Informe o nome.';
  else if (String(changes.nome).length > 200) errors.nome = 'Use até 200 caracteres no nome.';
  const optional = (name: string, max: number) => {
    const value = text(name); changes[name] = value || null;
    if (value.length > max) errors[name] = `Use até ${max} caracteres.`;
  };
  if (kind === 'clients') { optional('codigo', 80); optional('descricao', 4000); }
  if (kind === 'types') optional('sigla', 30);
  if (kind === 'cells') {
    optional('codigo', 80);
    const order = text('ordem');
    if (order && (!/^\d+$/.test(order) || Number(order) > 1_000_000)) errors.ordem = 'Informe um número inteiro entre 0 e 1.000.000 ou deixe vazio.';
    changes.ordem = order ? Number(order) : null;
    // The internal indice is generated by SQL on creation and preserved on edit.
  }
  return { changes: changes as SaveCatalogInput['changes'], errors };
}
export type CatalogAttempt =
  | { action: 'save'; payload: SaveCatalogInput }
  | { action: 'delete'; payload: DeleteCatalogInput };

/** A retry must preserve both the exact PostgreSQL version and the first body. */
export function freezeCatalogAttempt(attempt: CatalogAttempt): CatalogAttempt {
  const payload = attempt.action === 'save' ? Object.freeze({ ...attempt.payload, changes: Object.freeze({ ...attempt.payload.changes }) }) : Object.freeze({ ...attempt.payload });
  return Object.freeze({ action: attempt.action, payload }) as CatalogAttempt;
}
export function confirmsCatalogDeletion(name: string, confirmation: string): boolean {
  return !!name.trim() && confirmation.trim() === name.trim();
}
export function catalogFailureState(result: Extract<WebActionResult, { ok: false }>) {
  return { uncertain: ['UNAVAILABLE', 'CORP_UNAVAILABLE'].includes(result.code), stale: ['PT409', '40001', 'P0002'].includes(result.code),
    unauthorized: ['42501', 'CORP_UNAUTHORIZED', 'CORP_FORBIDDEN'].includes(result.code) };
}
